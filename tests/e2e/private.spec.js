import { test, expect } from '@playwright/test';
import { openTools, closeTools, findPerson, personDetails, openAccount } from '../helpers/workspace.cjs';

const origin = 'http://127.0.0.1:43175';
const password = 'private browser password for tests';

test('private workspace setup, publication, invitation, sharing, logout, and revocation work end to end', async ({ page, browser }) => {
  test.setTimeout(60000);
  await page.goto(origin);
  await expect(page.getByRole('heading', { name: 'Set up your private workspace' })).toBeVisible();
  await page.getByLabel('Username', { exact: true }).fill('browser-owner');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByLabel('Setup token').fill('browser-test-setup-secret-at-least-32-characters');
  await page.getByRole('button', { name: 'Create owner account' }).click();
  await expect(page.getByRole('heading', { name: 'Rootline', exact: true })).toBeVisible();
  await openAccount(page);
  await expect(page.getByText('Signed in as browser-owner', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => Object.keys(localStorage))).toEqual([]);
  await findPerson(page, 'Elena');
  await page.locator('.people-results button').click();
  await page.getByRole('button', { name: 'Privacy and sharing', exact: true }).click();
  const privacy = page.getByRole('dialog', { name: 'Privacy for Elena Vasquez' });
  await privacy.getByLabel('Living status').selectOption('DECEASED');
  await privacy.getByLabel('Approve basic details for viewers and links').check();
  await privacy.getByRole('button', { name: 'Save privacy settings' }).click();
  await expect(privacy).toBeHidden();
  await page.getByRole('button', { name: 'Show descendants' }).click();
  await expect(page.locator('[data-center-person-id]')).toHaveAttribute('data-center-person-id', 'elena');
  await expect(page.getByRole('heading', { name: 'Elena Vasquez', exact: true })).toBeVisible();
  await openTools(page, 'Sharing');
  await page.getByRole('button', { name: 'Manage tree access' }).click();
  const sharing = page.getByRole('dialog', { name: 'Tree access and sharing' });
  await sharing.getByLabel('Invited username').fill('browser-viewer');
  await sharing.getByRole('button', { name: 'Create invitation link' }).click();
  const invitation = await sharing.getByLabel('Invitation link', { exact: true }).inputValue();
  const viewerContext = await browser.newContext();
  const viewer = await viewerContext.newPage();
  await viewer.goto(invitation);
  await expect(viewer.getByRole('heading', { name: 'Accept tree invitation' })).toBeVisible();
  await viewer.getByLabel('Password', { exact: true }).fill(password);
  await viewer.getByRole('button', { name: 'Accept invitation', exact: true }).click();
  await expect(viewer.getByRole('heading', { name: 'The Lineage of Elena Vasquez' })).toBeVisible();
  await expect(viewer.getByRole('button', { name: 'Add person', exact: true })).toHaveCount(0);
  await expect(viewer.getByRole('button', { name: 'Download full tree backup' })).toHaveCount(0);
  await expect(viewer.getByRole('button', { name: 'Manage tree access' })).toHaveCount(0);
  expect(await viewer.evaluate(() => document.body.innerText)).not.toContain('Aria Hartwell');
  expect(await viewer.evaluate(() => Object.keys(localStorage))).toEqual([]);
  await openTools(viewer, 'Import and export');
  for (const name of ['Backups and history', 'Research', 'Sharing', 'Browser drafts']) {
    await expect(viewer.getByRole('button', { name, exact: true })).toHaveCount(0);
  }
  await viewer.getByRole('button', { name: 'Export GEDCOM', exact: true }).click();
  await expect(viewer.getByRole('dialog', { name: 'GEDCOM export preview' })).toContainText('1 people');
  await viewer.getByRole('button', { name: 'Close GEDCOM export preview', exact: true }).click();
  await sharing.getByLabel('Invited username').fill('browser-editor');
  await sharing.getByLabel('Invitation role').selectOption('EDITOR');
  await sharing.getByRole('button', { name: 'Create invitation link' }).click();
  await expect(sharing.getByLabel('Invitation link', { exact: true })).not.toHaveValue(invitation);
  const editorInvitation = await sharing.getByLabel('Invitation link', { exact: true }).inputValue();
  const editorContext = await browser.newContext({ viewport: { width: 375, height: 812 } }), editor = await editorContext.newPage();
  await editor.goto(editorInvitation);
  await editor.getByLabel('Password', { exact: true }).fill(password);
  await editor.getByRole('button', { name: 'Accept invitation', exact: true }).click();
  await openTools(editor, 'Backups and history');
  await expect(editor.getByRole('button', { name: 'Download full tree backup', exact: true })).toBeVisible();
  await expect(editor.getByRole('button', { name: 'Sharing', exact: true })).toHaveCount(0);
  await closeTools(editor);
  await editor.getByRole('button', { name: 'Select Aria Hartwell', exact: true }).click();
  await personDetails(editor);
  await editor.getByRole('button', { name: 'Edit person', exact: true }).click();
  await editor.getByRole('dialog').getByLabel('Notes').fill('Private editor draft retained after failure');
  await editor.route('**/api/trees/*/people/aria', route => route.fulfill({ status: 503, json: { error: 'Temporary save failure' } }), { times: 1 });
  await editor.getByRole('button', { name: 'Save person', exact: true }).click();
  await expect(editor.getByRole('dialog').getByRole('alert')).toHaveText('Temporary save failure');
  await expect(editor.getByRole('dialog').getByLabel('Notes')).toHaveValue('Private editor draft retained after failure');
  await editor.route('**/api/auth/session', route => route.abort(), { times: 1 });
  await editor.route('**/api/trees/*/family-data', route => route.abort(), { times: 1 });
  await editor.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(editor.getByText('Account service is unavailable. Unsaved forms are retained in memory while reconnecting.')).toBeVisible();
  await expect(editor.getByText('Tree access could not be checked. Unsaved forms are retained in memory while reconnecting.')).toBeVisible();
  await expect(editor.getByRole('dialog').getByLabel('Notes')).toHaveValue('Private editor draft retained after failure');
  await editor.getByRole('button', { name: 'Save person', exact: true }).click();
  await expect(editor.getByRole('dialog')).toBeHidden();
  expect(await editor.evaluate(() => Object.keys(localStorage))).toEqual([]);
  await expect(editor.getByRole('button', { name: 'Manage tree access' })).toHaveCount(0);
  await sharing.getByLabel('Role for browser-editor').selectOption('VIEWER');
  await sharing.getByRole('button', { name: 'Review role for browser-editor', exact: true }).click();
  await sharing.getByRole('button', { name: 'Confirm access change' }).click();
  await expect(editor.getByRole('button', { name: 'Edit person', exact: true })).toHaveCount(0, { timeout: 12000 });
  await expect(editor.getByRole('heading', { name: 'The Lineage of Elena Vasquez' })).toBeVisible();
  expect(await editor.evaluate(() => document.body.innerText)).not.toContain('Private editor draft');
  await sharing.getByLabel('Shared archive label').fill('Approved relatives');
  await sharing.getByRole('button', { name: 'Create read-only link' }).click();
  const link = await sharing.getByLabel('Read-only share link', { exact: true }).inputValue();
  const anonymousContext = await browser.newContext(), anonymous = await anonymousContext.newPage();
  await anonymous.goto(link);
  await expect(anonymous.getByRole('heading', { name: 'The Lineage of Elena Vasquez' })).toBeVisible();
  await anonymous.getByRole('button', { name: 'Show descendants' }).click();
  await anonymous.reload();
  await expect(anonymous.getByRole('heading', { name: 'Descendants of Elena Vasquez' })).toBeVisible();
  expect(new URL(anonymous.url()).searchParams.has('share')).toBe(true);
  expect(new URL(anonymous.url()).searchParams.has('tree')).toBe(false);
  await sharing.getByRole('button', { name: 'Revoke Approved relatives', exact: true }).click();
  await sharing.getByRole('button', { name: 'Confirm access change' }).click();
  await expect(anonymous.getByRole('alert')).toContainText('Access is unavailable', { timeout: 12000 });
  await sharing.getByRole('button', { name: 'Remove browser-viewer', exact: true }).click();
  await sharing.getByRole('button', { name: 'Confirm access change' }).click();
  await expect(viewer.getByRole('alert')).toContainText('Access is unavailable', { timeout: 12000 });
  expect(await viewer.evaluate(() => document.body.innerText)).not.toContain('Elena Vasquez');
  await sharing.getByRole('button', { name: 'Close Tree access and sharing', exact: true }).click();
  await closeTools(page);
  await openAccount(page);
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sign in to Rootline' })).toBeVisible();
  expect(await page.evaluate(() => Object.keys(localStorage))).toEqual([]);
  await page.getByLabel('Username', { exact: true }).fill('browser-owner');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await openAccount(page);
  await expect(page.getByText('Signed in as browser-owner', { exact: true })).toBeVisible();
  await openAccount(page);
  await page.getByRole('button', { name: 'Change password', exact: true }).click();
  await page.keyboard.press('Escape');
  await expect(page.locator('.account-menu summary')).toBeFocused();
  await openAccount(page);
  await page.getByRole('button', { name: 'Change password', exact: true }).click();
  await page.getByLabel('Current password', { exact: true }).fill(password);
  await page.getByLabel('New password', { exact: true }).fill(`${password} changed`);
  await page.getByRole('button', { name: 'Save password and sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sign in to Rootline' })).toBeVisible();
  await viewerContext.close(); await anonymousContext.close(); await editorContext.close();
});
