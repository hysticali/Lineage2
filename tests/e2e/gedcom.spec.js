import { test, expect } from '@playwright/test';
import { openTools } from '../helpers/workspace.cjs';

import fs from 'node:fs/promises';

test('GEDCOM browser import previews records, retains provenance, and exports a reimportable tree', async ({ page }) => {
  const bytes = await fs.readFile('tests/fixtures/evidence.ged');
  await page.goto('http://127.0.0.1:43174');
  await openTools(page, 'Import and export');
  await page.getByLabel('Import GEDCOM', { exact: true }).setInputFiles({ name: 'evidence.ged', mimeType: 'text/plain', buffer: bytes });
  let dialog = page.getByRole('dialog', { name: 'GEDCOM import preview' });
  await expect(dialog).toContainText('7 people · 4 families · 1 sources · 1 media records');
  await expect(dialog).toContainText('unsupported structures');
  await dialog.getByRole('textbox', { name: 'New tree name' }).fill('Browser GEDCOM family');
  await dialog.getByRole('button', { name: 'Confirm GEDCOM import' }).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByRole('heading', { name: 'The Lineage of Alex de la Cruz' })).toBeVisible();
  const treeId = new URL(page.url()).searchParams.get('tree');
  await page.getByRole('button', { name: 'Select Alex de la Cruz', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Parent families' })).toContainText('Adopted');
  await page.getByRole('button', { name: 'Records and evidence', exact: true }).click();
  dialog = page.getByRole('dialog');
  await expect(dialog.getByText('BET 1899 AND 1901 · Montréal, Canada', { exact: true })).toBeVisible();
  await expect(dialog.getByText('Referenced file: photos/register.jpg. Its bytes were not imported; add an attachment to store the original file.').first()).toBeVisible();
  await dialog.getByRole('button', { name: 'Close Records and evidence — Alex de la Cruz' }).click();
  await openTools(page, 'Import and export');
  await page.getByRole('button', { name: 'Import provenance', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Import provenance' });
  const originalPromise = page.waitForEvent('download');
  await dialog.getByRole('link', { name: 'Download original source' }).click();
  const original = await originalPromise;
  expect(await fs.readFile(await original.path())).toEqual(bytes);
  await dialog.getByRole('button', { name: 'Close Import provenance' }).click();
  await openTools(page, 'Import and export');
  await page.getByRole('button', { name: 'Export GEDCOM', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'GEDCOM export preview' });
  await expect(dialog).toContainText('7 people · 4 families · 1 sources');
  const exportPromise = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Download GEDCOM file', exact: true }).click();
  const exported = await exportPromise;
  const output = await fs.readFile(await exported.path());
  expect(output.toString()).toContain('_RESEARCH Retain this extension');
  await dialog.getByRole('button', { name: 'Close GEDCOM export preview' }).click();
  await openTools(page, 'Import and export');
  await page.getByLabel('Import GEDCOM', { exact: true }).setInputFiles({ name: 'round-trip.ged', mimeType: 'text/plain', buffer: output });
  dialog = page.getByRole('dialog', { name: 'GEDCOM import preview' });
  await expect(dialog).toContainText('7 people · 4 families · 1 sources · 1 media records');
  await dialog.getByRole('button', { name: 'Confirm GEDCOM import' }).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByRole('heading', { name: 'The Lineage of Alex de la Cruz' })).toBeVisible();
  expect(new URL(page.url()).searchParams.get('tree')).not.toBe(treeId);
});

test('GEDCOM browser preview prevents invalid imports and rejects invalid UTF-8', async ({ page }) => {
  const bytes = await fs.readFile('tests/fixtures/evidence.ged');
  await page.goto('http://127.0.0.1:43174');
  await openTools(page, 'Import and export');
  await page.getByLabel('Import GEDCOM', { exact: true }).setInputFiles({ name: 'cycle.ged', mimeType: 'text/plain', buffer: Buffer.from(bytes.toString().replace('1 CHIL @VOID@', '1 CHIL @I4@')) });
  const dialog = page.getByRole('dialog', { name: 'GEDCOM import preview' });
  await expect(dialog.getByRole('alert').first()).toContainText('ancestry cycle');
  await expect(dialog.getByRole('button', { name: 'Confirm GEDCOM import' })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Close GEDCOM import preview' }).click();
  await openTools(page, 'Import and export');
  await page.getByLabel('Import GEDCOM', { exact: true }).setInputFiles({ name: 'bad.ged', mimeType: 'text/plain', buffer: Buffer.from([0xc0, 0xaf]) });
  await expect(page.getByRole('region', { name: 'GEDCOM exchange' }).getByRole('alert')).toBeVisible();
  await expect(page.getByRole('dialog', { name: 'GEDCOM import preview' })).toBeHidden();
});

test('existing-tree import reviews matches, supports explicit duplicate merge, and recovers the original tree', async ({ page }) => {
  const source = await fs.readFile('tests/fixtures/evidence.ged', 'utf8');
  const origin = 'http://127.0.0.1:43174';
  const preview = await (await page.request.post(`${origin}/api/gedcom/preview`, { data: { source } })).json();
  const imported = await (await page.request.post(`${origin}/api/gedcom/import`, { data: { requestId: crypto.randomUUID(), source, checksum: preview.checksum, rootReference: '@I1@', name: 'Existing-tree browser import' } })).json();
  await page.goto(`${origin}/?tree=${imported.treeId}`);
  await expect(page.getByRole('heading', { name: 'The Lineage of Alex de la Cruz' })).toBeVisible();
  const rootId = new URL(page.url()).searchParams.get('person');
  await openTools(page, 'Import and export');
  await page.getByRole('combobox', { name: 'Import destination', exact: true }).selectOption('current');
  await openTools(page, 'Import and export');
  await page.getByLabel('Import GEDCOM', { exact: true }).setInputFiles({ name: 'matching.ged', mimeType: 'text/plain', buffer: Buffer.from(source) });
  let dialog = page.getByRole('dialog', { name: 'GEDCOM import preview' });
  await expect(dialog.getByRole('region', { name: 'Possible import matches' })).toContainText('Alex de la Cruz');
  await expect(dialog.getByRole('button', { name: 'Confirm GEDCOM import', exact: true })).toBeDisabled();
  await dialog.getByRole('checkbox', { name: 'I reviewed possible matches and understand that people remain separate until explicitly merged.' }).check();
  await dialog.getByRole('button', { name: 'Confirm GEDCOM import', exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect(page.locator('header')).toContainText('14 people');
  expect(new URL(page.url()).searchParams.get('person')).toBe(rootId);
  await openTools(page, 'Research');
  await page.getByRole('button', { name: 'Review duplicates', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Duplicate people review' });
  await dialog.locator('.duplicate-candidates button').filter({ hasText: 'Alex de la Cruz' }).click();
  await dialog.getByRole('button', { name: 'Preview person merge', exact: true }).click();
  await dialog.getByRole('button', { name: 'Confirm person merge', exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect(page.locator('header')).toContainText('13 people');
  await openTools(page, 'Backups and history');
  await page.getByRole('button', { name: 'Edit history', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Preview recovery before revision 1', exact: true }).click();
  await page.getByRole('dialog', { name: 'Database restore preview' }).getByRole('button', { name: 'Confirm database restore', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'GEDCOM import preview' })).toBeHidden();
  await expect(page.locator('header')).toContainText('7 people');
  await expect(page.getByRole('heading', { name: 'The Lineage of Alex de la Cruz' })).toBeVisible();
});
